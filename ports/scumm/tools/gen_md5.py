"""Cut ScummVM's scumm-md5.h down to the SCUMM v3/v4 PC games this port
runs, and write src/scumm/fj_md5.h.

usage: tools/gen_md5.py upstream/scummvm-v2.2.0/engines/scumm/scumm-md5.h
"""
import re
import sys

KEEP = {
    "loom": {"EGA", "No AdLib", "VGA", "Steam", "PC-Engine"},
    "indy3": {"EGA", "No AdLib", "VGA", "Steam"},
    "monkey": {"EGA", "VGA", "Demo", "No AdLib"},
    "pass": {""},
}
PLATFORMS = {"kPlatformDOS", "kPlatformUnknown", "kPlatformAtariST", "kPlatformWindows",
             "kPlatformPCEngine"}

row = re.compile(r'\s*\{ "([0-9a-f]{32})", "([^"]*)", "([^"]*)", "([^"]*)", (-?\d+), Common::(\w+), Common::(\w+) \},')
out = []
for line in open(sys.argv[1]):
    m = row.match(line)
    if not m:
        continue
    md5, gameid, variant, extra, size, lang, plat = m.groups()
    # Japanese Loom PC-Engine needs the System Card's kanji font (no SJIS here)
    if plat == "kPlatformPCEngine" and lang != "EN_ANY":
        continue
    if gameid in KEEP and variant in KEEP[gameid] and plat in PLATFORMS:
        out.append('\t{ "%s", "%s", "%s", "%s", %s, Common::%s, Common::%s },' %
                   (md5, gameid, variant, extra, size, lang, plat))

print("""/* Generated by tools/gen_md5.py from ScummVM 2.2.0 engines/scumm/scumm-md5.h.
 * Only SCUMM v3/v4 PC versions of Loom, Indiana Jones 3, Monkey Island 1
 * and Passport to Adventure, plus English Loom for the PC Engine CD.
 * DO NOT EDIT.
 */

namespace Scumm {

struct MD5Table {
	const char *md5;
	const char *gameid;
	const char *variant;
	const char *extra;
	int32 filesize;
	Common::Language language;
	Common::Platform platform;
};

static const MD5Table md5table[] = {""")
print("\n".join(out))
print("""	{ 0, 0, 0, 0, 0, Common::UNK_LANG, Common::kPlatformUnknown }
};

} // End of namespace Scumm""")
