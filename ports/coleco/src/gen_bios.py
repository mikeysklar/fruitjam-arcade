"""Generate cv_bios.h: a small open replacement for the ColecoVision BIOS.

    python3 gen_bios.py > cv_bios.h

This is new code, not derived from the Coleco ROM. It only provides what
cartridges that drive the hardware themselves need:

  $0000  reset: DI, SP=$73FF, mute the PSG, VDP display off, then jump through
         the cartridge start pointer at $800A if $8000 holds AA 55 or 55 AA
         (no title screen). Without a cartridge header it halts.
  $0008-$0038  RST n -> JP $800C,$800F,...,$801E (cartridge vectors)
  $0066  NMI -> JP $8021 (the VDP frame interrupt)
  $0069  60 (NTSC)
  $006C  pointer 128 bytes past an ASCII font starting at char $20 (CVBasic
         reads it); the font is font8x8 (public domain)
  $1F61-$1FFD  the documented OS7 jump table addresses. These are implemented:
         FILL_VRAM $1F82, TURN_OFF_SOUND $1FD6, WRITE_REGISTER $1FD9,
         READ_REGISTER $1FDC, WRITE_VRAM $1FDF, READ_VRAM $1FE2.
         Every other entry returns immediately.
"""
import os

rom = bytearray([0xFF] * 0x2000)


def put(addr, data):
    rom[addr:addr + len(data)] = bytes(data)
    return addr + len(data)


def jp(addr):
    return [0xC3, addr & 0xFF, addr >> 8]


BOOT = 0x0100
FONT = 0x1500
put(0x0000, [0xF3, 0x31, 0xFF, 0x73] + jp(BOOT))  # DI; LD SP,$73FF; JP boot
for i, vec in enumerate(range(0x800C, 0x8021, 3)):
    put(8 * (i + 1), jp(vec))  # RST $08..$38
put(0x0066, jp(0x8021))  # NMI
put(0x0069, [60, 0x00, 0x00])
put(0x006C, [(FONT + 128) & 0xFF, (FONT + 128) >> 8])

MUTE = [0x3E, 0x9F, 0xD3, 0xFF, 0x3E, 0xBF, 0xD3, 0xFF,  # LD A,n; OUT ($FF),A x4
        0x3E, 0xDF, 0xD3, 0xFF, 0x3E, 0xFF, 0xD3, 0xFF]
boot = MUTE + [
    0xDB, 0xBF,  # IN A,($BF)       reset the VDP latch
    0x3E, 0x00, 0xD3, 0xBF, 0x3E, 0x80, 0xD3, 0xBF,  # R0 = $00
    0x3E, 0x80, 0xD3, 0xBF, 0x3E, 0x81, 0xD3, 0xBF,  # R1 = $80 (16K, blank, no NMI)
    0x2A, 0x00, 0x80,  # LD HL,($8000)
    0x7D, 0xFE, 0xAA,  # LD A,L; CP $AA
    0x20, 0x05,  # JR NZ,chk2
    0x7C, 0xFE, 0x55,  # LD A,H; CP $55
    0x28, 0x0A,  # JR Z,go
    # chk2:
    0x7D, 0xFE, 0x55,  # LD A,L; CP $55
    0x20, 0x09,  # JR NZ,nocart
    0x7C, 0xFE, 0xAA,  # LD A,H; CP $AA
    0x20, 0x04,  # JR NZ,nocart
    # go:
    0x2A, 0x0A, 0x80,  # LD HL,($800A)
    0xE9,  # JP (HL)
    # nocart:
    0x76, 0x18, 0xFD,  # HALT; JR nocart
]
end = put(BOOT, boot)

# OS7-compatible routines (register use as documented for the OS7 entries).
routines = {}
addr = 0x0200
code = {
    "ret": [0xC9],
    "write_register": [0x79, 0xD3, 0xBF, 0x78, 0xF6, 0x80, 0xD3, 0xBF, 0xC9],
    "read_register": [0xDB, 0xBF, 0xC9],
    # HL=source, DE=VRAM address, BC=count
    "write_vram": [0x7B, 0xD3, 0xBF, 0x7A, 0xF6, 0x40, 0xD3, 0xBF,
                   0x7E, 0xD3, 0xBE, 0x23, 0x0B, 0x78, 0xB1, 0x20, 0xF7, 0xC9],
    # HL=dest, DE=VRAM address, BC=count
    "read_vram": [0x7B, 0xD3, 0xBF, 0x7A, 0xE6, 0x3F, 0xD3, 0xBF,
                  0xDB, 0xBE, 0x77, 0x23, 0x0B, 0x78, 0xB1, 0x20, 0xF7, 0xC9],
    # HL=VRAM address, DE=count, A=value
    "fill_vram": [0x4F, 0x7D, 0xD3, 0xBF, 0x7C, 0xF6, 0x40, 0xD3, 0xBF,
                  0x79, 0xD3, 0xBE, 0x1B, 0x7A, 0xB3, 0x20, 0xF8, 0xC9],
    "turn_off_sound": MUTE + [0xC9],
}
for name, c in code.items():
    routines[name] = addr
    addr = put(addr, c)
assert addr < FONT

for a in range(0x1F61, 0x1FFE, 3):
    put(a, jp(routines["ret"]))
for a, name in [(0x1F82, "fill_vram"), (0x1FD6, "turn_off_sound"),
                (0x1FD9, "write_register"), (0x1FDC, "read_register"),
                (0x1FDF, "write_vram"), (0x1FE2, "read_vram")]:
    put(a, jp(routines[name]))

font = []
here = os.path.dirname(os.path.abspath(__file__))
for line in open(os.path.join(here, "font8x8.txt")):
    line = line.split("#")[0].split()
    font += [int(v, 16) for v in line]
assert len(font) == 96 * 8
put(FONT, font)

print("// Generated by gen_bios.py, do not edit. MIT; font8x8 is public domain.")
print("static const uint8_t cv_open_bios[8192] = {")
for i in range(0, 0x2000, 16):
    print("    " + " ".join("0x%02X," % b for b in rom[i:i + 16]))
print("};")
