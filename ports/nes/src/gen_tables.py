"""Generate nes_tables.h: NES palette in RGB888/RGB565/RGB332 and APU mixer tables.

Run: python3 gen_tables.py > nes_tables.h

The palette is the common 2C02 approximation (as used by agnes and many
others). Mixer tables follow the nesdev wiki APU mixer formulas, scaled to Q15.
"""

PAL = """
7c7c7c 0000fc 0000bc 4428bc 940084 a80020 a81000 881400 503000 007800 006800 005800 004058 000000 000000 000000
bcbcbc 0078f8 0058f8 6844fc d800cc e40058 f83800 e45c10 ac7c00 00b800 00a800 00a844 008888 000000 000000 000000
f8f8f8 3cbcfc 6888fc 9878f8 f878f8 f85898 f87858 fca044 f8b800 b8f818 58d854 58f898 00e8d8 787878 000000 000000
fcfcfc a4e4fc b8b8f8 d8b8f8 f8b8f8 f8a4c0 f0d0b0 fce0a8 f8d878 d8f878 b8f8b8 b8f8d8 00fcfc f8d8f8 000000 000000
""".split()
rgb = [(int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16)) for c in PAL]
assert len(rgb) == 64


def rows(vals, fmt, n=8):
    out = []
    for i in range(0, len(vals), n):
        out.append("    " + ", ".join(fmt % v for v in vals[i:i + n]) + ",")
    return "\n".join(out)


print("// Generated by gen_tables.py. Do not edit.")
print("static const uint8_t nes_pal_rgb[64 * 3] = {")
print(rows([v for c in rgb for v in c], "0x%02X", 24))
print("};")
print("static const uint16_t nes_pal565[64] = {")
print(rows([((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in rgb], "0x%04X"))
print("};")
print("static const uint8_t nes_pal332[64] = {")
print(rows([((r >> 5) << 5) | ((g >> 5) << 2) | (b >> 6) for r, g, b in rgb], "0x%02X", 16))
print("};")
pul = [0] + [round(95.52 / (8128.0 / n + 100) * 32767) for n in range(1, 31)]
tnd = [0] + [round(163.67 / (24329.0 / n + 100) * 32767) for n in range(1, 203)]
# Pattern byte -> 8 bytes of 0/1, leftmost pixel (bit 7) in the lowest byte.
spread = []
for b in range(256):
    px = [(b >> (7 - i)) & 1 for i in range(8)]
    spread.append((sum(px[i] << (8 * i) for i in range(4)), sum(px[4 + i] << (8 * i) for i in range(4))))
print("static const uint32_t nes_spread[256][2] = {")
for i in range(0, 256, 4):
    print("    " + " ".join("{0x%08X, 0x%08X}," % spread[j] for j in range(i, i + 4)))
print("};")
print("static const uint8_t nes_rev8[256] = {")
print(rows([int("{:08b}".format(b)[::-1], 2) for b in range(256)], "0x%02X", 16))
print("};")
print("static const uint16_t apu_pulse_table[31] = {")
print(rows(pul, "%d", 16))
print("};")
print("static const uint16_t apu_tnd_table[203] = {")
print(rows(tnd, "%d", 16))
print("};")
