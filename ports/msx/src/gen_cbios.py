"""Write cbios.h from the C-BIOS MSX1 ROMs in cbios/ (see cbios/README.txt).

    python3 gen_cbios.py > cbios.h
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def array(name, path, size):
    data = open(os.path.join(HERE, "cbios", path), "rb").read()
    assert len(data) == size, path
    out = ["static const uint8_t %s[%d] = {" % (name, size)]
    for i in range(0, size, 16):
        out.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    out.append("};")
    return "\n".join(out)


print("// Generated by gen_cbios.py from cbios/*.rom. Do not edit.")
print("//")
print("// C-BIOS 0.29a MSX1 main ROM and logo ROM, NOT MIT: these bytes are under")
print("// the C-BIOS BSD-style license, see cbios/LICENSE.txt.")
print("#ifndef MSX_CBIOS_H")
print("#define MSX_CBIOS_H")
print(array("cbios_main", "cbios_main_msx1.rom", 32768))
print(array("cbios_logo", "cbios_logo_msx1.rom", 16384))
print("#endif")
