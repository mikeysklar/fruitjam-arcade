"""Write palette.h from MAME's Atari 7800 NTSC palette (BSD-3-Clause, see
LICENSE.mame). The table is the "25.7 phase shift" set that MAME uses by
default, in src/mame/atari/a7800.cpp:

    python3 gen_palette.py path/to/a7800.cpp > palette.h
"""
import re
import sys

src = open(sys.argv[1]).read()
start = src.index("PALETTE - 25.7 PHASE SHIFT")
block = src[start:src.index("static constexpr rgb_t a7800_colors", start)]
hues = {}
for m in re.finditer(r"#define (NTSC_\w+) \\\n((?:.*\\\n)*.*\))", block):
    rgb = re.findall(r"rgb_t\(0x(\w\w),0x(\w\w),0x(\w\w)", m.group(2))
    hues[m.group(1)] = [tuple(int(c, 16) for c in t) for t in rgb]
order = re.search(r"a7800_colors\[256\] =\s*\{([^}]*)\}", src[start:]).group(1).split(",")
colors = [c for name in order if name.strip() for c in hues[name.strip()]]
assert len(colors) == 256
print("// Generated by gen_palette.py from MAME's a7800.cpp NTSC palette.")
print("// Copyright Dan Boris, Fabio Priuli, Mike Saarna, Robert Tuccitto.")
print("// SPDX-License-Identifier: BSD-3-Clause (see LICENSE.mame)")
print("static const uint32_t a78_rgb[256] = {")
for i in range(0, 256, 8):
    print("    " + " ".join("0x%02X%02X%02X," % c for c in colors[i:i + 8]))
print("};")
